// تنسيق موحّد للتاريخ + الوقت: dd/mm/yy "على|at" HH:MM
if (!function_exists('format_datetime_short')) {
    function format_datetime_short($time): string
    {
        global $lang;
        if ($time === null || $time === '') {
            return '';
        }

        $ts = is_numeric($time) ? (int)$time : @strtotime((string)$time);
        if (!$ts) {
            return '';
        }

        $connector = ($lang === 'ar') ? 'على' : 'at';

        return date('d/m/Y', $ts) . ' ' . $connector . ' ' . date('H:i', $ts);
    }
}